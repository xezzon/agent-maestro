//! 存储锁的毒化标记：被毒化的是**锁**，不是存储的内容。
//!
//! 毒化发生在「其它命令持锁期间 panic」——锁本身进了毒化状态，此后所有加锁
//! 都失败。它不属于任何领域：配置存储（[`crate::errors::ConfigError`]）与偏好
//! 存储（[`crate::errors::PreferencesError`]）各经一段 `From` 把它折进自己的
//! 「存储不可用」，故两处的文案各自贴切（毒化的不是配置内容，也不是偏好内容）。

