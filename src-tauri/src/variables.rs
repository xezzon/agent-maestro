//! 全局变量表（ADR 0015）：变量名 → 默认值，供投影前的占位符插值。
//!
//! 本模块是中立的一层：变量表既被配置存储读写，也被插值与插件服务消费。
//! 它的形状若住在其中任一方（存储层或插值层），两个模块就会互相依赖成环。
//! 这里只声明形状，不含行为——行为归各自的消费方。

use std::collections::BTreeMap;

/// 全局变量表：变量名 → 默认值。
///
/// 空表是合法状态（`${EMPTY}` 解析为空串即按未配置端点处理，ADR 0015）。
pub(crate) type Variables = BTreeMap<String, String>;
